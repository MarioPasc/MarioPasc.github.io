"""Refresh _data/metrics.yml with the citation metrics of a Google Scholar profile.

Google Scholar has no API and blocks most data-centre IPs, so run this locally
before pushing:

    python3 scripts/update_metrics.py

The file is only rewritten when the profile page parses correctly.
"""

from __future__ import annotations

import argparse
import datetime as dt
import logging
import re
import sys
import urllib.request
from dataclasses import dataclass
from pathlib import Path

SCHOLAR_USER = "47ei0IcAAAAJ"
PROFILE_URL = f"https://scholar.google.es/citations?user={SCHOLAR_USER}&hl=en"
OUTPUT = Path(__file__).resolve().parent.parent / "_data" / "metrics.yml"
# Scholar serves a captcha page to clients without a browser user agent.
USER_AGENT = (
    "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 "
    "(KHTML, like Gecko) Chrome/126.0 Safari/537.36"
)

logger = logging.getLogger("update_metrics")


class MetricsError(Exception):
    """Raised when the Scholar profile cannot be fetched or parsed."""


@dataclass(frozen=True)
class ScholarMetrics:
    """All-time citation metrics shown in a Scholar profile sidebar."""

    citations: int
    h_index: int
    i10_index: int


def fetch_profile(url: str, timeout: float = 20.0) -> str:
    """Download the profile page.

    Parameters
    ----------
    url : str
        Google Scholar profile URL.
    timeout : float
        Socket timeout in seconds.

    Returns
    -------
    str
        Page HTML.

    Raises
    ------
    MetricsError
        If the request fails.
    """
    request = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    try:
        with urllib.request.urlopen(request, timeout=timeout) as response:
            return response.read().decode("utf-8", errors="replace")
    except OSError as exc:
        raise MetricsError(f"could not fetch {url}: {exc}") from exc


def parse_metrics(html: str) -> ScholarMetrics:
    """Extract citations, h-index and i10-index from the profile HTML.

    The sidebar table holds six ``gsc_rsb_std`` cells: (all, since year) for
    citations, h-index and i10-index, in that order.

    Parameters
    ----------
    html : str
        Profile page HTML.

    Returns
    -------
    ScholarMetrics
        All-time values.

    Raises
    ------
    MetricsError
        If the table is missing, e.g. because Scholar returned a captcha.
    """
    cells = re.findall(r'class="gsc_rsb_std">(\d+)<', html)
    if len(cells) != 6:
        raise MetricsError(f"expected 6 metric cells, found {len(cells)}")
    return ScholarMetrics(
        citations=int(cells[0]), h_index=int(cells[2]), i10_index=int(cells[4])
    )


def write_yaml(metrics: ScholarMetrics, path: Path, today: dt.date) -> None:
    """Write the metrics file read by _includes/metrics.html.

    Parameters
    ----------
    metrics : ScholarMetrics
        Values to store.
    path : Path
        Destination file.
    today : datetime.date
        Retrieval date written alongside the values.
    """
    path.write_text(
        "# Generated by scripts/update_metrics.py; do not edit by hand.\n"
        "source: Google Scholar\n"
        f"profile: https://scholar.google.es/citations?user={SCHOLAR_USER}\n"
        f"retrieved: {today.isoformat()}\n"
        f"citations: {metrics.citations}\n"
        f"h_index: {metrics.h_index}\n"
        f"i10_index: {metrics.i10_index}\n",
        encoding="utf-8",
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--dry-run", action="store_true", help="print, do not write")
    args = parser.parse_args()
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")

    try:
        metrics = parse_metrics(fetch_profile(PROFILE_URL))
    except MetricsError as exc:
        logger.error("%s; %s left unchanged", exc, OUTPUT)
        return 1

    logger.info("%s", metrics)
    if not args.dry_run:
        write_yaml(metrics, OUTPUT, dt.date.today())
        logger.info("wrote %s", OUTPUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
